#!/usr/bin/env python3
"""Typeset the saved poems with the saved AI illustrations into a three-page PDF.

This is a presentation of poems, not the assignment report. It never generates
or rewrites poem text and makes no network or generative AI calls.
"""

import argparse
import json
from pathlib import Path

from reportlab.lib.colors import HexColor
from reportlab.lib.pagesizes import A4
from reportlab.lib.utils import ImageReader
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.pdfgen.canvas import Canvas

ROOT = Path(__file__).resolve().parents[1]
PAPER = HexColor("#F6F2EA")
INK = HexColor("#20383C")
MUTED = HexColor("#647374")
RULE = HexColor("#C9C9BC")


def tracked(canvas, text, x, y, size=9, tracking=1.8):
    canvas.saveState()
    block = canvas.beginText(x, y)
    block.setFont("Helvetica", size)
    block.setCharSpace(tracking)
    block.textLine(text)
    canvas.drawText(block)
    canvas.restoreState()


def build(poem_path, assets, output):
    poems = json.loads(poem_path.read_text(encoding="utf-8"))
    if len(poems) != 3:
        raise ValueError("This anthology layout expects the three selected poems.")
    images = []
    for i, poem in enumerate(poems, 1):
        if len(poem["lines"]) != 8:
            raise ValueError("Each selected poem must contain eight lines.")
        image_path = assets / "images" / f"{i:02}_{poem['theme']}.png"
        images.append(ImageReader(str(image_path)))
        saved_text = (assets / "texts" / f"{i:02}_{poem['theme']}.txt").read_text(encoding="utf-8")
        if saved_text != poem["text"]:
            raise ValueError(f"Saved poem text does not match {poem['title']}.")
    output.parent.mkdir(parents=True, exist_ok=True)
    canvas = Canvas(str(output), pagesize=A4, pageCompression=1, invariant=1)
    canvas.setTitle("Small Weather - three illustrated poems")
    canvas.setAuthor("Small Weather | Python grammar, with Codex assistance")
    canvas.setSubject("Poems generated by poet.py; illustrations created using the built-in image generation tool.")
    width, height = A4
    margin = 46
    usable = width - 2 * margin
    themes = {"rain": "CITY / WAITING", "tide": "HARBOUR / RELEASE", "frost": "GARDEN / RETURN"}
    for i, (poem, artwork) in enumerate(zip(poems, images), 1):
        canvas.setFillColor(PAPER)
        canvas.rect(0, 0, width, height, stroke=0, fill=1)
        canvas.setFillColor(INK)
        tracked(canvas, "SMALL WEATHER", margin, height - 40, size=10, tracking=2.7)
        canvas.setFillColor(MUTED)
        canvas.setFont("Helvetica", 8)
        canvas.drawRightString(width - margin, height - 40, f"{i:02} / {len(poems):02}")

        # Contain the complete image; never crop the artwork.
        image_w, image_h = artwork.getSize()
        box_top, box_h = height - 66, 336
        scale = min(usable / image_w, box_h / image_h)
        drawn_w, drawn_h = image_w * scale, image_h * scale
        canvas.drawImage(artwork, margin + (usable - drawn_w) / 2,
                         box_top - drawn_h, width=drawn_w, height=drawn_h, mask="auto")

        canvas.setFillColor(MUTED)
        tracked(canvas, themes[poem["theme"]], margin, 414, size=7.5, tracking=1.4)
        canvas.setFillColor(INK)
        title_size = 30
        if stringWidth(poem["title"], "Times-Roman", title_size) > usable:
            raise ValueError("Title exceeds available width.")
        canvas.setFont("Times-Roman", title_size)
        canvas.drawString(margin, 375, poem["title"])

        body_size = 13
        canvas.setFont("Times-Roman", body_size)
        y = 339
        for index, line in enumerate(poem["lines"]):
            if stringWidth(line, "Times-Roman", body_size) > usable:
                raise ValueError("Poem line would wrap; adjust the layout without changing its text.")
            canvas.drawString(margin, y, line)
            y -= 19
            if index % 2 == 1:
                y -= 12

        canvas.setStrokeColor(RULE)
        canvas.setLineWidth(0.5)
        canvas.line(margin, 96, width - margin, 96)
        canvas.setFillColor(MUTED)
        canvas.setFont("Helvetica", 7.5)
        canvas.drawString(margin, 79, "Eight lines, an ordinary object, a change in the weather.")
        canvas.drawString(margin, 65, "Poem: Small Weather grammar generator. Illustration: generative AI.")
        canvas.drawRightString(width - margin, 43, f"Seed {poem['seed']}  /  {poem['theme']}")
        canvas.bookmarkPage(poem["theme"])
        canvas.addOutlineEntry(poem["title"], poem["theme"], level=0)
        canvas.showPage()
    canvas.save()
    print(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--poems", type=Path, default=ROOT / "poems" / "selected.json")
    parser.add_argument("--assets", type=Path, default=ROOT / "presentation")
    parser.add_argument("--output", type=Path, default=ROOT / "output" / "pdf" / "Small_Weather_Anthology.pdf")
    args = parser.parse_args()
    build(args.poems, args.assets, args.output)


if __name__ == "__main__":
    main()
